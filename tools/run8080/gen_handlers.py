"""Generate the 256-entry 8080 dispatch used by run8080.asm."""

from __future__ import annotations
from pathlib import Path

PAIRS = ("bc", "de", "hl", "sp")
ALU = ("do_add", "do_adc", "do_sub", "do_sbb", "do_ana", "do_xra", "do_ora", "do_cmp")
NOPS = {0x00, 0x08, 0x10, 0x18, 0x20, 0x28, 0x30, 0x38, 0xF3, 0xFB}
PREFIX = {0xCB, 0xDD, 0xED, 0xFD}

lines: list[str | None] = [None] * 256


def put(op: int, body: str) -> None:
    if lines[op] is not None:
        raise SystemExit(f"opcode {op:02X} assigned twice")
    lines[op] = body


def block(op: int, *stmts: str) -> None:
    body = []
    for stmt in stmts:
        if stmt.startswith("|"):
            body.append(stmt[1:])
        else:
            body.append("\t" + stmt)
    put(op, "\n".join(body))


for op in range(256):
    if op in NOPS:
        block(op, "jmp\tdispatch")
    elif op in PREFIX:
        block(op, "jmp\tstop_prefix")
    elif op == 0x76:
        block(op, "jmp\tdo_hlt")
    elif op & 0xC0 == 0x40:
        dst, src = (op >> 3) & 7, op & 7
        block(op, f"lda\t#{src}", "jsr\tgetreg", "sta\tnew",
              f"lda\t#{dst}", "sta\tregidx", "lda\tnew", "jsr\tsetreg",
              "jmp\tdispatch")
    elif op & 0xC0 == 0x80:
        kind, src = (op >> 3) & 7, op & 7
        block(op, f"lda\t#{src}", "jsr\tgetreg", "sta\tval", f"jmp\t{ALU[kind]}")
    elif op & 0xC7 == 0xC6:
        kind = (op >> 3) & 7
        block(op, "jsr\tfetch8", "sta\tval", f"jmp\t{ALU[kind]}")
    elif op & 0xC7 == 0x06:
        dst = (op >> 3) & 7
        block(op, "jsr\tfetch8", "sta\tnew", f"lda\t#{dst}", "sta\tregidx",
              "lda\tnew", "jsr\tsetreg", "jmp\tdispatch")
    elif op & 0xC7 == 0x04:
        reg = (op >> 3) & 7
        block(op, f"lda\t#{reg}", "jsr\tgetreg", "jmp\tdo_inr")
    elif op & 0xC7 == 0x05:
        reg = (op >> 3) & 7
        block(op, f"lda\t#{reg}", "jsr\tgetreg", "jmp\tdo_dcr")
    elif op & 0xCF == 0x01:
        zp = PAIRS[(op >> 4) & 3]
        block(op, "jsr\tfetch16", f"ldx\t#{zp}", "lda\tfetlo", "ldy\tfethi",
              "jsr\tmap_ea", "jmp\tdispatch")
    elif op & 0xCF == 0x09:
        zp = PAIRS[(op >> 4) & 3]
        block(op, f"ldx\t#{zp}", "jmp\tdo_dad")
    elif op & 0xCF == 0x03:
        zp = PAIRS[(op >> 4) & 3]
        block(op, f"inw\t{zp}", f"ldx\t#{zp}", "jsr\tfixup_inc", "jmp\tdispatch")
    elif op & 0xCF == 0x0B:
        zp = PAIRS[(op >> 4) & 3]
        block(op, f"dew\t{zp}", f"ldx\t#{zp}", "jsr\tfixup_dec", "jmp\tdispatch")
    elif op & 0xC7 == 0xC2:
        cc = (op >> 3) & 7
        block(op, "jsr\tfetch16", f"lda\t#{cc}", "jsr\tcond", f"beq\tt{op:02X}",
              "jmp\tdispatch", f"|t{op:02X}\tjmp\tdo_take")
    elif op & 0xC7 == 0xC4:
        cc = (op >> 3) & 7
        block(op, "jsr\tfetch16", f"lda\t#{cc}", "jsr\tcond", f"beq\tt{op:02X}",
              "jmp\tdispatch", f"|t{op:02X}\tjmp\tdo_call_take")
    elif op & 0xC7 == 0xC0:
        cc = (op >> 3) & 7
        block(op, f"lda\t#{cc}", "jsr\tcond", f"beq\tt{op:02X}",
              "jmp\tdispatch", f"|t{op:02X}\tjmp\tdo_ret")
    elif op & 0xC7 == 0xC7:
        block(op, f"lda\t#${op & 0x38:02X}", "jmp\tdo_rst")
    elif op & 0xCF == 0xC5:
        pair = (op >> 4) & 3
        if pair == 3:
            block(op, "jmp\tdo_push_psw")
        else:
            block(op, f"ldx\t#{PAIRS[pair]}", "jmp\tdo_push")
    elif op & 0xCF == 0xC1:
        pair = (op >> 4) & 3
        if pair == 3:
            block(op, "jmp\tdo_pop_psw")
        else:
            block(op, f"ldx\t#{PAIRS[pair]}", "jmp\tdo_pop")

MISC = {
    0x02: ("ldx\t#bc", "jmp\tdo_stax"),
    0x12: ("ldx\t#de", "jmp\tdo_stax"),
    0x0A: ("ldx\t#bc", "jmp\tdo_ldax"),
    0x1A: ("ldx\t#de", "jmp\tdo_ldax"),
    0x22: ("jmp\tdo_shld",),
    0x2A: ("jmp\tdo_lhld",),
    0x32: ("jmp\tdo_sta",),
    0x3A: ("jmp\tdo_lda",),
    0x07: ("jmp\tdo_rlc",),
    0x0F: ("jmp\tdo_rrc",),
    0x17: ("jmp\tdo_ral",),
    0x1F: ("jmp\tdo_rar",),
    0x27: ("jmp\tdo_daa",),
    0x2F: ("jmp\tdo_cma",),
    0x37: ("jmp\tdo_stc",),
    0x3F: ("jmp\tdo_cmc",),
    0xC3: ("jmp\tdo_jmp",),
    0xC9: ("jmp\tdo_ret",),
    0xD9: ("jmp\tdo_ret",),
    0xCD: ("jmp\tdo_call",),
    0xD3: ("jmp\tdo_out",),
    0xDB: ("jmp\tdo_in",),
    0xE3: ("jmp\tdo_xthl",),
    0xE9: ("jmp\tdo_pchl",),
    0xEB: ("jmp\tdo_xchg",),
    0xF9: ("jmp\tdo_sphl",),
}
for op, stmts in MISC.items():
    block(op, *stmts)

missing = [op for op, text in enumerate(lines) if text is None]
if missing:
    raise SystemExit("missing " + ",".join(f"{op:02X}" for op in missing))


def szp(value: int) -> int:
    sign = 0x80 if value & 0x80 else 0
    zero = 0x40 if value == 0 else 0
    parity = 0x04 if bin(value).count("1") % 2 == 0 else 0
    return sign | zero | parity


out = ["", "; generated by gen_handlers.py", ""]
for op, text in enumerate(lines):
    out.append(f"op{op:02X}")
    out.append(text)
    out.append("")

out.append("tablo")
for op in range(128):
    out.append(f"\t.word\top{op:02X}")
out.append("tabhi")
for op in range(128, 256):
    out.append(f"\t.word\top{op:02X}")
out.append("szp")
for base in range(0, 256, 16):
    nums = ",".join(f"${szp(base + i):02X}" for i in range(16))
    out.append(f"\t.byte\t{nums}")
out.append("")

Path(__file__).with_name("handlers.asm").write_text("\n".join(out))
print("handlers.asm", sum(1 for _ in out), "lines")
