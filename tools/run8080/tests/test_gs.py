"""One case for each 45GS02 operation the 8080 core uses, and one Attic copy.

45GS02 is the MEGA65's 6502-family processor.  DMAgic is its block-copy
engine.  Attic RAM is the memory above the first 8 megabytes.
"""

from pathlib import Path

from bench.sim.dos65 import DOS65Machine


def run(code: bytes) -> DOS65Machine:
    root = Path("/tmp")
    machine = DOS65Machine(root)
    machine.load(code)
    machine.run(2000)
    return machine


def test_ldz_tab_tba_and_base_page():
    # LDZ, TAB, a zero-page store while B is 3, TBA, then BRK.
    code = bytes([
        0xA3, 0x07,          # LDZ #7
        0xA9, 0x03, 0x5B,    # LDA #3 / TAB
        0xA9, 0x5A, 0x85, 0x10,
        0x7B,                # TBA
        0x8D, 0x00, 0x04,
        0x00,
    ])
    machine = run(code)
    assert machine.exit_reason == "brk"
    assert machine.z_register == 7
    assert machine.memory[0x0310] == 0x5A
    assert machine.memory[0x0400] == 3


def test_indirect_32_bank4_and_attic():
    code = bytes([
        0xA3, 0x00,
        0xA9, 0x00, 0x85, 0x10,
        0xA9, 0x21, 0x85, 0x11,
        0xA9, 0x04, 0x85, 0x12,
        0xA9, 0x00, 0x85, 0x13,
        0xA9, 0x5A,
        0xEA, 0x92, 0x10,     # STA [zp],Z into bank 4
        0xA9, 0x00,
        0xEA, 0xB2, 0x10,     # LDA [zp],Z
        0x8D, 0x00, 0x04,
        0xA9, 0x00, 0x85, 0x10,
        0xA9, 0x00, 0x85, 0x11,
        0xA9, 0x00, 0x85, 0x12,
        0xA9, 0x08, 0x85, 0x13,
        0xA9, 0xA5,
        0xEA, 0x92, 0x10,     # STA [zp],Z into Attic
        0x00,
    ])
    machine = run(code)
    assert machine.exit_reason == "brk"
    assert machine.bank(4)[0x2100] == 0x5A
    assert machine.memory[0x0400] == 0x5A
    assert machine.attic[0] == 0xA5


def test_indirect_16_with_z():
    code = bytes([
        0xA9, 0x00, 0x85, 0x20,
        0xA9, 0x04, 0x85, 0x21,
        0xA9, 0x77, 0x8D, 0x02, 0x04,
        0xA3, 0x02,
        0xB2, 0x20,           # LDA (zp),Z
        0x8D, 0x10, 0x04,
        0xA9, 0x88,
        0x92, 0x20,           # STA (zp),Z
        0x00,
    ])
    machine = run(code)
    assert machine.memory[0x0410] == 0x77
    assert machine.memory[0x0402] == 0x88


def test_inw_and_dew_use_the_relocated_page():
    code = bytes([
        0xA9, 0x03, 0x5B,
        0xA9, 0xFF, 0x85, 0x10,
        0xA9, 0x00, 0x85, 0x11,
        0xE3, 0x10,           # INW
        0xA5, 0x10, 0x48,
        0xA5, 0x11, 0x48,
        0xC3, 0x10,           # DEW back
        0xA5, 0x10, 0x48,
        0xA5, 0x11, 0x48,
        0xA9, 0x00, 0x5B,
        0x68, 0x8D, 0x03, 0x04,
        0x68, 0x8D, 0x02, 0x04,
        0x68, 0x8D, 0x01, 0x04,
        0x68, 0x8D, 0x00, 0x04,
        0x00,
    ])
    machine = run(code)
    assert machine.exit_reason == "brk"
    assert machine.memory[0x0400] == 0x00   # low after INW
    assert machine.memory[0x0401] == 0x01   # high after INW
    assert machine.memory[0x0402] == 0xFF   # low after DEW
    assert machine.memory[0x0403] == 0x00


def test_bra_neg_asr_asw_and_jmp_indexed():
    code = bytes([
        0x80, 0x01,           # BRA over the next byte
        0x00,
        0xA9, 0x01, 0x42,     # NEG
        0x8D, 0x00, 0x04,
        0x08, 0x68, 0x8D, 0x01, 0x04,
        0xA9, 0x81, 0x43,     # ASR
        0x8D, 0x02, 0x04,
        0x08, 0x68, 0x8D, 0x03, 0x04,
        0xA9, 0x01, 0x8D, 0x10, 0x04,
        0xA9, 0x80, 0x8D, 0x11, 0x04,
        0xCB, 0x10, 0x04,     # ASW
        0xA9, 0x80, 0x8D, 0x30, 0x04,
        0xA9, 0x02, 0x8D, 0x31, 0x04,
        0xA2, 0x00,
        0x7C, 0x30, 0x04,     # JMP (abs,X)
        0x00,
    ])
    # The indexed jump lands at $0220, which load() does not contain.
    landing = bytes([0xA9, 0x42, 0x8D, 0x04, 0x04, 0x00])
    machine = DOS65Machine(Path("/tmp"))
    machine.load(code)
    machine.memory[0x0280:0x0280 + len(landing)] = landing
    machine.run(2000)
    assert machine.exit_reason == "brk"
    assert machine.memory[0x0400] == 0xFF          # NEG 1
    assert machine.memory[0x0401] & 0x81 == 0x81   # N and C
    assert machine.memory[0x0402] == 0xC0          # ASR of $81
    assert machine.memory[0x0403] & 0x01 == 0x01   # C from bit 0
    assert machine.memory[0x0410] == 0x02          # ASW of $8001
    assert machine.memory[0x0411] == 0x00
    assert machine.memory[0x0404] == 0x42          # landing store


def test_enhanced_dma_copies_chip_ram_into_attic():
    code = bytes([
        0xA9, 0x00, 0xA2, 0xD5, 0xA0, 0x00, 0xA3, 0xB5, 0x5C,
        0xA9, 0x05, 0x8D, 0x02, 0xD7,
        0xA9, 0x08, 0x8D, 0x01, 0xD7,
        0xA9, 0x00, 0x8D, 0x04, 0xD7,
        0x8D, 0x05, 0xD7,
        0x00,
    ])
    listing = bytes([
        0x81, 0x80, 0x00,
        0x00, 0x04, 0x00,
        0x00, 0x30, 0x05,
        0x10, 0x00, 0x00,
        0x00, 0x00,
    ])
    machine = DOS65Machine(Path("/tmp"))
    machine.load(code)
    machine.memory[0x0800:0x0800 + len(listing)] = listing
    machine.memory[0x3000:0x3004] = b"WXYZ"
    machine.run(2000)
    assert machine.exit_reason == "brk"
    assert machine.attic[0x10:0x14] == b"WXYZ"
    assert machine.dma_jobs[-1][2] == 0
    assert machine.dma_jobs[-1][5] == 0x80      # megabyte number, bits 20-27


def test_store_to_address_zero_is_the_speed_register():
    code = bytes([0xA9, 0x41, 0x8D, 0x00, 0x00, 0x00])
    machine = DOS65Machine(Path("/tmp"))
    machine.memory[0] = 0x4C
    machine.load(code)
    machine.run(200)
    assert machine.speed_log == [0x41]
    assert machine.memory[0] == 0x4C
